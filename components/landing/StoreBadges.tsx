import {
  APP_STORE_QR,
  APP_STORE_URL,
  PLAY_STORE_QR,
  PLAY_STORE_URL,
} from "@/lib/store-links";
import { AppleLogo, GooglePlayLogo } from "./icons";

const STORES = [
  {
    name: "App Store",
    kicker: "Download on the",
    href: APP_STORE_URL,
    qr: APP_STORE_QR,
    Logo: AppleLogo,
  },
  {
    name: "Google Play",
    kicker: "Get it on",
    href: PLAY_STORE_URL,
    qr: PLAY_STORE_QR,
    Logo: GooglePlayLogo,
  },
] as const;

/** The two store buttons. */
export function StoreBadgeRow() {
  return (
    <div className="badges">
      {STORES.map(({ name, kicker, href, Logo }) => (
        <a
          key={name}
          className="store-badge"
          href={href}
          target="_blank"
          rel="noopener noreferrer"
        >
          <Logo />
          <span className="store-badge-text">
            <small>{kicker}</small>
            <strong>{name}</strong>
          </span>
        </a>
      ))}
    </div>
  );
}

/**
 * Scannable codes for visitors reading on a desktop.
 *
 * Plain `<img>` rather than `next/image`: these are vector QR masters
 * generated by `scripts/generate-store-qr.js`, and running them through the
 * raster optimizer would only risk softening the module edges that a phone
 * camera needs to be crisp.
 */
export function StoreQrRow() {
  return (
    <div className="qr-row">
      {STORES.map(({ name, qr }) => (
        <figure className="qr-card" key={name}>
          <div className="qr-code">
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img
              src={qr}
              alt={`QR code linking to 4 Our Life on the ${name}`}
              width={140}
              height={140}
              loading="lazy"
              decoding="async"
            />
          </div>
          <figcaption>Scan to get it on the {name}</figcaption>
        </figure>
      ))}
    </div>
  );
}
